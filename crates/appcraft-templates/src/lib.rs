const GITIGNORE_TEXT: &str = "/target\n*.db-shm\n*.db-wal\n.env\n";

/// Emit the desktop_egui viewer tree. Pure + deterministic: same inputs,
/// byte-identical outputs — golden-tested. Returns (relative_path, content).
pub fn render_desktop_egui(
    app_title: &str,
    package_name: &str,
    db_file_name: &str,
    tables: &[String],
) -> Vec<(String, String)> {
    let table_list = tables
        .iter()
        .map(|t| format!("    \"{t}\",\n"))
        .collect::<String>();
    let main_rs = MAIN_RS_TEMPLATE
        .replace("__APP_TITLE__", app_title)
        .replace("__DB_FILE__", db_file_name)
        .replace("__TABLES__", &table_list)
        .replace("__PACKAGE__", package_name);
    let cargo_toml = CARGO_TOML_TEMPLATE.replace("__PACKAGE__", package_name);
    let readme = README_TEMPLATE
        .replace("__APP_TITLE__", app_title)
        .replace("__DB_FILE__", db_file_name);
    vec![
        ("Cargo.toml".to_string(), cargo_toml),
        ("src/main.rs".to_string(), main_rs),
        ("README.md".to_string(), readme),
        (".gitignore".to_string(), GITIGNORE_TEXT.to_string()),
    ]
}
