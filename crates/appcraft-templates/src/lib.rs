fn db_rows(db: &str, sql: &str) -> Result<(Vec<String>, Vec<Vec<String>>), String> {
    let conn = Connection::open(db).map_err(|e| e.to_string())?;
    let mut stmt = conn.prepare(sql).map_err(|e| e.to_string())?;
    let cols: Vec<String> = stmt.column_names().iter().map(|s| s.to_string()).collect();
    let n = cols.len();
    let mut out = Vec::new();
    let mut q = stmt.query([]).map_err(|e| e.to_string())?;
    while let Some(row) = q.next().map_err(|e| e.to_string())? {
        let mut vals = Vec::new();
        for i in 0..n {
            let v: Value = row.get(i).map_err(|e| e.to_string())?;
            vals.push(value_to_string(&v));
        }
        out.push(vals);
    }
    Ok((cols, out))
}

fn table_html(cols: &[String], rows: &[Vec<String>]) -> String {
    let mut h = String::from("<table><tr>");
    for c in cols {
        h.push_str(&format!("<th>{}</th>", esc(c)));
    }
    h.push_str("</tr>");
    for r in rows {
        h.push_str("<tr>");
        for cell in r {
            h.push_str(&format!("<td>{}</td>", esc(cell)));
        }
        h.push_str("</tr>");
    }
    h.push_str("</table>");
    h
}

