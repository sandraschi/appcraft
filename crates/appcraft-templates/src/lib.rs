fn table_columns(db_path: &str, table: &str) -> Result<Vec<String>, String> {
    let conn = Connection::open(db_path).map_err(|e| e.to_string())?;
    let mut stmt = conn
        .prepare(&format!("PRAGMA table_info({table})"))
        .map_err(|e| e.to_string())?;
    let names = stmt
        .query_map([], |row| row.get::<_, String>(1))
        .map_err(|e| e.to_string())?;
    let mut out = Vec::new();
    for name in names {
        out.push(name.map_err(|e| e.to_string())?);
    }
    Ok(out)
}

fn table_rows(
    db_path: &str,
    table: &str,
    width: usize,
    needle: &str,
) -> Result<(Vec<Vec<String>>, usize), String> {
    let conn = Connection::open(db_path).map_err(|e| e.to_string())?;
    let total: i64 = conn
        .query_row(&format!("SELECT COUNT(*) FROM {table}"), [], |r| r.get(0))
        .map_err(|e| e.to_string())?;
    let mut stmt = conn
        .prepare(&format!("SELECT * FROM {table} LIMIT {ROW_LIMIT}"))
        .map_err(|e| e.to_string())?;
    let mut out = Vec::new();
    let mut q = stmt.query([]).map_err(|e| e.to_string())?;
    while let Some(row) = q.next().map_err(|e| e.to_string())? {
        let mut vals = Vec::with_capacity(width);
        let mut hit = needle.is_empty();
        for i in 0..width {
            let v: Value = row.get(i).map_err(|e| e.to_string())?;
            let s = value_to_string(&v);
            if !hit && s.to_lowercase().contains(needle) {
                hit = true;
            }
            vals.push(s);
        }
        if hit {
            out.push(vals);
        }
    }
    Ok((out, usize::try_from(total.max(0)).unwrap_or(0)))
}

struct ViewerApp {
    db_path: String,
    tables: Vec<String>,
    selected: usize,
    search: String,
    columns: Vec<String>,
    rows: Vec<Vec<String>>,
    total: usize,
    error: Option<String>,
}

impl ViewerApp {
    fn new(db_path: String) -> Self {
        let mut app = Self {
            db_path,
            tables: TABLES.iter().map(|s| s.to_string()).collect(),
            selected: 0,
            search: String::new(),
            columns: Vec::new(),
            rows: Vec::new(),
            total: 0,
            error: None,
        };
        app.reload();
        app
    }

    fn reload(&mut self) {
        self.error = None;
        if self.tables.is_empty() {
            self.error = Some("No tables in this database.".to_string());
            return;
        }
        if self.selected >= self.tables.len() {
            self.selected = 0;
        }
        let table = self.tables[self.selected].clone();
        let needle = self.search.to_lowercase();
        match table_columns(&self.db_path, &table) {
            Ok(cols) => {
                let width = cols.len();
                self.columns = cols;
                match table_rows(&self.db_path, &table, width, &needle) {
                    Ok((rows, total)) => {
                        self.rows = rows;
                        self.total = total;
                    }
                    Err(e) => self.error = Some(e),
                }
            }
            Err(e) => self.error = Some(e),
        }
    }
}

impl eframe::App for ViewerApp {
    fn ui(&mut self, ui: &mut egui::Ui, _frame: &mut eframe::Frame) {
        egui::Panel::top("title").show(ui, |ui| {
            ui.heading(APP_TITLE);
            ui.label(format!("{} — {} rows shown", self.db_path, self.rows.len()));
        });
        egui::Panel::left("tables").show(ui, |ui| {
            ui.heading("Tables");
            let mut picked: Option<usize> = None;
            for (i, t) in self.tables.iter().enumerate() {
                if ui.selectable_label(self.selected == i, t).clicked() {
                    picked = Some(i);
                }
            }
            if let Some(i) = picked {
                self.selected = i;
                self.reload();
            }
        });
        egui::CentralPanel::default().show(ui, |ui| {
            if let Some(err) = self.error.clone() {
                ui.colored_label(egui::Color32::RED, err);
                return;
            }
            ui.horizontal(|ui| {
                ui.label("Search:");
                let resp = ui.text_edit_singleline(&mut self.search);
                if resp.changed() {
                    self.reload();
                }
                ui.label(format!("{} of {} rows", self.rows.len(), self.total));
            });
            egui::ScrollArea::both().show(ui, |ui| {
                egui::Grid::new("rows").striped(true).show(ui, |ui| {
                    for c in &self.columns {
                        ui.strong(c);
                    }
                    ui.end_row();
                    for r in &self.rows {
                        for cell in r {
                            ui.label(cell);
                        }
                        ui.end_row();
                    }
                });
            });
        });
    }
}

fn main() -> eframe::Result<()> {
    let db_path = std::env::args()
        .nth(1)
        .unwrap_or_else(|| DEFAULT_DB.to_string());
    let options = eframe::NativeOptions::default();
    eframe::run_native(
        APP_TITLE,
        options,
        Box::new(|_cc| Ok(Box::new(ViewerApp::new(db_path)))),
    )
}
