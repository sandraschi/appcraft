async fn onboarding_submit(
    State(state): State<Arc<AppState>>,
    Form(f): Form<HashMap<String, String>>,
) -> Result<Html<String>, (StatusCode, String)> {
    let get = |k: &str| f.get(k).cloned().unwrap_or_default();
    let name = get("full_name").trim().to_string();
    if name.is_empty() {
        return Err((StatusCode::BAD_REQUEST, "Full name is required.".to_string()));
    }
    let payload = serde_json::json!({
        "full_name": name,
        "date_of_birth": get("date_of_birth"),
        "gender": get("gender"),
        "phone": get("phone"),
        "email": get("email"),
        "insurance_provider": get("insurance_provider"),
        "allergies": get("allergies"),
        "emergency_contact": get("emergency_contact"),
    })
    .to_string();
    let conn = Connection::open(&state.db_path).map_err(|e| (StatusCode::INTERNAL_SERVER_ERROR, e.to_string()))?;
    conn.execute(
        "INSERT INTO portal_requests (req_type, payload, status) VALUES ('onboarding', ?1, 'new')",
        params![payload],
    )
    .map_err(|e| (StatusCode::INTERNAL_SERVER_ERROR, e.to_string()))?;
    let id = conn.last_insert_rowid();
    Ok(shell(
        "Request received",
        format!(
            "<p>Thank you, {}. Your reference is <strong>ONB-{}</strong>. The practice will call you back.</p><p><a href=\"/\">Back home</a></p>",
            esc(&name),
            id
        ),
    ))
}

